def heading_of(comment):
    for start, head in GROUPS:
        if comment.lower().startswith(start.lower()):
            return head
    raise SystemExit(f'problems.py: a group of codes the page does not know: «{comment}» — add it to GROUPS')


def messages(lib):
    text = lib.read('profiles/problems.py')
    msgs = literals(text, 'MESSAGES')['MESSAGES']
    order = _messages_block(text)
    if {c for _, c in order} != set(msgs):
        missing = sorted(set(msgs) - {c for _, c in order})
        raise SystemExit(f'the reader of problems.py lost some codes: {", ".join(missing[:8])}')
    return msgs, order


def messages_page(lib):
    msgs, order = messages(lib)
    levels = _levels(lib)
    out = [banner(lib)]
    groups = []
    for g, c in order:
        if not groups or groups[-1][0] != g:
            groups.append((g, []))
        groups[-1][1].append(c)
    for g, cs in groups:
        head = heading_of(g)
        out.append(f'\n{head}\n{"~" * max(len(head), 4)}\n\n')
        rows = []
        for c in cs:
            en = placeholders(msgs[c][0])
            lvl = ' / '.join(sorted(levels.get(c, set()))) or '—'
            rows.append([code(c), lvl, rst_text(en)])
        out.append(list_table(['Code', 'Level', 'What it says'], rows, [26, 12, 62]))
    return ''.join(out)


# ── the Italian catalogue of the validator's page ──────────────────────────

def _po_entries(text):
    """Very small reader of a .po file: (msgid, msgstr, start, end) of each entry."""
    out = []
    for m in re.finditer(r'(?ms)^msgid ((?:"(?:[^"\\]|\\.)*"\n?)+)msgstr ((?:"(?:[^"\\]|\\.)*"\n?)+)', text):
        def join(block):
            return ''.join(ast.literal_eval(x) for x in re.findall(r'"(?:[^"\\]|\\.)*"', block))
        out.append((join(m.group(1)), join(m.group(2)), m.start(2), m.end(2)))
    return out


def _po_string(s):
    esc = s.replace('\\', '\\\\').replace('"', '\\"')
    if len(esc) < 70:
        return f'"{esc}"\n'
    words, lines, cur = re.split(r'(?<= )', esc), [], ''
    for w in words:
        if len(cur) + len(w) > 76 and cur:
            lines.append(cur)
            cur = ''
        cur += w
    lines.append(cur)
    return '""\n' + ''.join(f'"{x}"\n' for x in lines)


