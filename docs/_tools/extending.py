# ── the validator's sentences ───────────────────────────────────────────────

def _messages_block(text):
    """``(group, code)`` in the order of the source: the comment above a run of
    codes names their group."""
    start = text.index('MESSAGES')
    body = text[start:]
    end = body.index('\n}\n')
    group, out = 'reading', []
    for line in body[:end].splitlines()[1:]:
        m = re.match(r'^\s{4}#\s*(.+?)\s*$', line)
        if m:
            group = m.group(1)
            continue
        m = re.match(r'^\s{4}"([a-z0-9_]+)":\s*\(', line)
        if m:
            out.append((group, m.group(1)))
    return out


def _levels(lib):
    """code → the levels the library raises it with (scanned from the calls)."""
    files = [f for f in lib.files() if f.startswith(('profiles/', 'extensions/', 'em/')) and f.endswith('.py')]
    found = {}
    pat = re.compile(r'\.(error|warn|info)\(\s*"([a-z0-9_]+)"'
                     r'|Problem\(\s*"([a-z0-9_]+)"\s*,\s*(ERROR|WARNING|INFO)'
                     r'|\(\s*"(error|warning)"\s*,\s*"([a-z0-9_]+)"'
                     r'|\w+Error\.of\(\s*"([a-z0-9_]+)"'
                     r'|_change\(\s*\w+\s*,\s*"([a-z0-9_]+)"')
    for f in files:
        try:
            text = lib.read(f)
        except (OSError, subprocess.CalledProcessError):
            continue
        for m in pat.finditer(text):
            if m.group(2):
                lvl, c = {'error': 'error', 'warn': 'warning', 'info': 'info'}[m.group(1)], m.group(2)
            elif m.group(3):
                lvl, c = m.group(4).lower(), m.group(3)
            elif m.group(6):
                lvl, c = m.group(5), m.group(6)
            elif m.group(7):
                lvl, c = 'refusal', m.group(7)
            else:
                lvl, c = 'info', m.group(8)
            found.setdefault(c, set()).add(lvl)
    return found


def placeholders(s):
    """``{path}`` and ``{value!r}`` written as ‹path›, ‹value›: what the sentence fills in."""
    return re.sub(r'\{([a-z_]+)(?:![rs])?\}', r'‹\1›', s)


