def slots_page(lib):
    s = literals(lib.read('extensions/slots.py'), 'PHASE1', 'PHASE2', 'DRAWN2', 'READ_ONLY_SLOTS',
                 'COMMAND_SLOTS', 'FILE_SLOTS')
    rows = []
    names = list(s['PHASE1']) + [n for n in s['DRAWN2'] if n not in s['PHASE1']]
    for name in names:
        version = s['PHASE1'].get(name) or s['DRAWN2'].get(name)
        if name not in SLOT_WHERE:
            raise SystemExit(f'slot {name}: no line in SLOT_WHERE — say where it appears')
        kind = ('declared, not a command' if name == 'panel' else
                'reads only' if name in s['READ_ONLY_SLOTS'] else
                'returns a file' if name in s['FILE_SLOTS'] else
                'a command' if name in s['COMMAND_SLOTS'] else 'a call of the API')
        rows.append([code(f'{name}@{version}'), SLOT_WHERE[name], kind])
    later = [f'{n}@{v}' for n, v in s['PHASE2'].items() if n not in s['DRAWN2']]
    out = [banner(lib)]
    out.append(list_table(['Slot', 'Where it appears', 'What the command is'], rows, [24, 52, 24]))
    out.append('\nNames reserved for later versions, accepted by the validator with a warning '
               'and not drawn yet: ' + codes(later) + '.\n')
    return ''.join(out)


