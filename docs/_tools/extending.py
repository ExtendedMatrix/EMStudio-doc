def fill_it(lib, po_path):
    msgs, _ = messages(lib)
    en_to_it = {rst_text(placeholders(en)): rst_text(placeholders(it)) for en, it in msgs.values()}
    en_to_it.update(IT_WORDS)
    for c in msgs:
        en_to_it[code(c)] = code(c)
    text = open(po_path, encoding='utf-8').read()
    filled, parts, last = 0, [], 0
    for msgid, msgstr, a, b in _po_entries(text):
        if msgstr or msgid not in en_to_it:
            continue
        parts.append(text[last:a])
        parts.append(_po_string(en_to_it[msgid]))
        last = b
        filled += 1
    parts.append(text[last:])
    with open(po_path, 'w', encoding='utf-8') as fh:
        fh.write(''.join(parts))
    print(f'{po_path}: {filled} sentences of the validator filled in Italian')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('s3dgraphy', help='an s3Dgraphy checkout (read only)')
    ap.add_argument('--ref', help='a tag or commit of s3Dgraphy, read through git show')
    ap.add_argument('--fill-it', action='store_true',
                    help='fill the Italian catalogue of the validator page instead of writing the tables')
    a = ap.parse_args()
    lib = Library(a.s3dgraphy, a.ref)
    if a.fill_it:
        fill_it(lib, os.path.join(DOCS, 'locale', 'it', 'LC_MESSAGES', 'extending', 'validator.po'))
        return
    write(os.path.join(OUT, 'extending-slots.rst'), slots_page(lib))
    write(os.path.join(OUT, 'extending-sets.rst'), sets_page(lib))
    write(os.path.join(OUT, 'extending-messages.rst'), messages_page(lib))


if __name__ == '__main__':
    main()
