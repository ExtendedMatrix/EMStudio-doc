#!/usr/bin/env python3
"""Generate the reference tables of «Extending EMStudio» from s3Dgraphy's sources.

    .venv/bin/python docs/_tools/extending.py ~/Documents/GitHub/s3Dgraphy --ref <tag or commit>
    .venv/bin/python docs/_tools/extending.py ~/Documents/GitHub/s3Dgraphy --fill-it

The extensions of EMStudio are read and checked by s3Dgraphy, the library the
desktop application runs: the slots a command may appear in, the closed sets
of the manifest (permissions, hosts, capabilities, platforms, operations…),
and every sentence of the one validator, in English and in Italian. This
script reads them from an s3Dgraphy checkout — the working tree, or a tag or
commit through ``git show`` with ``--ref`` — and writes, never by hand:

* ``docs/reference/_generated/extending-slots.rst`` — the slots, their version,
  whether a command drawn there only reads;
* ``docs/reference/_generated/extending-sets.rst`` — the closed sets;
* ``docs/reference/_generated/extending-messages.rst`` — the validator's
  sentences, grouped as the source groups them, with their level.

The pages of ``docs/extending/`` include them. ``--fill-it`` fills the Italian
catalogue of the validator's page with the Italian sentences of the same
source (only empty strings), so the Italian manual says the words the Italian
validator prints. Nothing is written into the s3Dgraphy checkout.

Every value is read with ``ast`` from the literal assignments of the source;
a value that is not a literal stops the script with its name, instead of
guessing.
"""

import argparse
import ast
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.dirname(HERE)
OUT = os.path.join(DOCS, 'reference', '_generated')
sys.path.insert(0, HERE)
from emsource import list_table, rst_text, write  # noqa: E402


class Library:
    """A file of s3Dgraphy at a path, in the working tree or at a git ref."""

    def __init__(self, root, ref=None):
        self.root = os.path.abspath(os.path.expanduser(root))
        self.ref = ref
        if not os.path.isdir(os.path.join(self.root, 'src', 's3dgraphy')):
            raise SystemExit(f'{self.root}: not an s3Dgraphy checkout (no src/s3dgraphy)')

    def read(self, rel):
        rel = 'src/s3dgraphy/' + rel
        if self.ref:
            return subprocess.run(['git', '-C', self.root, 'show', f'{self.ref}:{rel}'],
                                  check=True, capture_output=True, text=True).stdout
        with open(os.path.join(self.root, rel), encoding='utf-8') as fh:
            return fh.read()

    def files(self):
        """The files of the package, relative to src/s3dgraphy/."""
        if self.ref:
            names = subprocess.run(['git', '-C', self.root, 'ls-tree', '-r', '--name-only', self.ref, 'src/s3dgraphy/'],
                                   check=True, capture_output=True, text=True).stdout.split()
            return [n[len('src/s3dgraphy/'):] for n in names]
        base = os.path.join(self.root, 'src', 's3dgraphy')
        return [os.path.relpath(os.path.join(d, f), base).replace(os.sep, '/')
                for d, _, fs in os.walk(base) if '__pycache__' not in d for f in fs]

    def version(self):
        m = re.search(r'^version\s*=\s*"([^"]+)"', self._pyproject(), re.M)
        return m.group(1) if m else '?'

    def _pyproject(self):
        if self.ref:
            return subprocess.run(['git', '-C', self.root, 'show', f'{self.ref}:pyproject.toml'],
                                  check=True, capture_output=True, text=True).stdout
        with open(os.path.join(self.root, 'pyproject.toml'), encoding='utf-8') as fh:
            return fh.read()

    def where(self):
        return f'{self.ref}' if self.ref else 'the working tree'


def literals(text, *names):
    """The literal values assigned to ``names`` at the top of a module."""
    tree = ast.parse(text)
    found = {}
    for node in tree.body:
        targets, value = [], None
        if isinstance(node, ast.Assign):
            targets, value = node.targets, node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets, value = [node.target], node.value
        for t in targets:
            if isinstance(t, ast.Name) and t.id in names:
                try:
                    found[t.id] = ast.literal_eval(value)
                except ValueError:
                    raise SystemExit(f'{t.id}: not a literal in the source — teach extending.py its new shape')
    missing = [n for n in names if n not in found]
    if missing:
        raise SystemExit(f'not found in the source: {", ".join(missing)}')
    return found


def banner(lib):
    return (f'..\n   GENERATED by docs/_tools/extending.py from s3Dgraphy {lib.version()} ({lib.where()}).\n'
            f'   Do not edit by hand: run docs/_tools/extending.py again (its docstring says how).\n\n')


def code(s):
    return f'``{s}``'


def codes(seq):
    return ', '.join(code(x) for x in seq)


